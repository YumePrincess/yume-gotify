const tables: Record<Language, TranslationTable> = {
  en,
  fr,
  ja,
  'zh-cn': zhCn,
  'zh-tw': zhTw
}

const interpolate = (message: string, values?: Values): string =>
  values
    ? message.replace(/\{(\w+)\}/g, (match, key: string) =>
        values[key] === undefined ? match : String(values[key])
      )
    : message

export const translateFor = (
  language: Language,
  key: TranslationKey,
  values?: Values
): string => interpolate(tables[language][key] ?? en[key], values)

export const translate = (key: TranslationKey, values?: Values): string => {
  const language = resolveLanguage(
    ((): LanguageChoice => {
      try {
        const cookie = document.cookie
          .split(';')
          .map((part) => part.trim())
          .find((part) => part.startsWith('yume-preference-language='))
        const value = cookie
          ? decodeURIComponent(cookie.split('=').slice(1).join('='))
          : window.localStorage.getItem('lang') || 'auto'
        return ['auto', 'en', 'fr', 'ja', 'zh-cn', 'zh-tw'].includes(value)
          ? (value as LanguageChoice)
          : 'auto'
      } catch {
        return 'auto'
      }
    })()
  )
  return translateFor(language, key, values)
}

interface I18nValue {
  language: Language
  languageChoice: LanguageChoice
  setLanguageChoice: (choice: LanguageChoice) => void
  t: (key: TranslationKey, values?: Values) => string
}

const I18nContext = React.createContext<I18nValue | null>(null)

export const I18nProvider: React.FC<React.PropsWithChildren> = ({
  children
}) => {
  const [languageChoice, setLanguageChoice] = useLanguagePreference()
  const language = resolveLanguage(languageChoice)
  const t = React.useCallback(
    (key: TranslationKey, values?: Values) =>
      translateFor(language, key, values),
    [language]
  )

  React.useEffect(() => {
    document.documentElement.lang = language
    document.title = t('brand')
  }, [language, t])

  const value = React.useMemo(
    () => ({ language, languageChoice, setLanguageChoice, t }),
    [language, languageChoice, setLanguageChoice, t]
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = (): I18nValue => {
  const value = React.useContext(I18nContext)
  if (!value) throw new Error('I18nProvider is missing')
  return value
}

